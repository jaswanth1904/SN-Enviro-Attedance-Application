// Reusable Late Check-In Escalation Dispatcher (After 10:30 AM IST)
const triggerLateCheckInEscalation = async (user, attendance) => {
    try {
        if (!user || !user.email) return;

        const checkInDate = new Date(attendance.timestamp || Date.now());
        const istDateStr = checkInDate.toLocaleDateString('en-CA', { timeZone: 'Asia/Kolkata' });
        const istDate = new Date(checkInDate.toLocaleString('en-US', { timeZone: 'Asia/Kolkata' }));
        const istHours = istDate.getHours();
        const istMinutes = istDate.getMinutes();
        const isLateCheckIn = istHours > 10 || (istHours === 10 && istMinutes >= 30);

        if (!isLateCheckIn) return;

        const Explanation = require('../models/Explanation');
        const crypto = require('crypto');
        const sendEmail = require('../utils/sendEmail');

        const startOfDay = new Date(`${istDateStr}T00:00:00.000+05:30`);
        const endOfDay = new Date(`${istDateStr}T23:59:59.999+05:30`);

        const existingExp = await Explanation.findOne({
            user: user._id || user.id,
            date: { $gte: startOfDay, $lte: endOfDay }
        });

        if (!existingExp) {
            const token = crypto.randomBytes(20).toString('hex');
            const timeStr = `${istHours.toString().padStart(2, '0')}:${istMinutes.toString().padStart(2, '0')} IST`;
            await Explanation.create({
                user: user._id || user.id,
                date: new Date(),
                reason: `Late Login (${timeStr} - After 10:30 AM cutoff)`,
                status: 'Pending Review',
                token: token
            });

            const baseUrl = process.env.FRONTEND_URL || 'https://attendance.snenviro.org';
            const explanationUrl = `${baseUrl}/explain-absence/${token}`;
            await sendEmail({
                email: user.email,
                subject: 'ESCALATION: Late Check-In Alert',
                message: `
                    <div style="font-family: Arial, sans-serif; padding: 24px; max-width: 600px; margin: auto; border: 1px solid #fee2e2; border-radius: 12px; background-color: #fffaf0;">
                        <h2 style="color: #dc2626; margin-top: 0;">⚠️ Late Check-In Escalation Alert</h2>
                        <p>Dear <strong>${user.name}</strong>,</p>
                        <p>Our records show your attendance check-in today was logged at <strong>${timeStr}</strong>, which is after the required <strong>10:30 AM IST</strong> cutoff.</p>
                        <div style="background-color: #ffffff; border-left: 4px solid #dc2626; padding: 12px; margin: 15px 0;">
                            <p style="margin: 0; font-size: 14px;"><strong>Reason Code:</strong> Late Login (Recorded after 10:30 AM IST)</p>
                            <p style="margin: 5px 0 0; font-size: 13px; color: #64748b;"><strong>Policy:</strong> Daily login must be marked before 10:30 AM IST.</p>
                        </div>
                        <p>Please click the button below to submit your official reason for review:</p>
                        <a href="${explanationUrl}" style="display:inline-block; padding: 12px 24px; background-color: #dc2626; color: #ffffff; text-decoration: none; border-radius: 6px; font-weight: bold;">Provide Explanation</a>
                        <hr style="border: none; border-top: 1px solid #fecaca; margin: 20px 0;">
                        <small style="color: #94a3b8;">Automated escalation generated by SN Enviro Attendance Portal via attendance@snenviro.in</small>
                    </div>
                `
            });
            console.log(`[ESCALATION] 🚨 Auto-Warning sent to ${user.email} (Check-in at ${timeStr}).`);
        }
    } catch (escalationErr) {
        console.error('[ESCALATION ERROR]', escalationErr.message);
    }
};

// @desc    Record attendance
// @route   POST /api/attendance
// @access  Private (Staff/Senior/Accountant/Engineer/Office)
exports.recordAttendance = async (req, res, next) => {
    try {
        const { siteId, latitude, longitude, selfieUrl, locationName, timestamp, onlyReverse } = req.body;
        if (latitude === undefined || longitude === undefined || latitude === null || longitude === null || isNaN(Number(latitude)) || isNaN(Number(longitude))) {
            return res.status(400).json({
                success: false,
                error: 'Valid latitude and longitude coordinates are required for attendance verification.'
            });
        }
        const { reverseGeocode, verifyPlantGeofence } = require('../utils/geo');

        // Run the strict 1000m Geofence check
        const geofence = verifyPlantGeofence(latitude, longitude);

        let actualLocationName;
        if (geofence.isAuthorized) {
            actualLocationName = geofence.plant.name;
        } else {
            actualLocationName = await reverseGeocode(latitude, longitude);
        }

        // Handle simple address detection for UI feedback
        if (onlyReverse) {
            return res.status(200).json({ success: true, address: actualLocationName });
        }

        // Compute IST check-in time for Late status determination (Cutoff: 10:30 AM IST)
        const checkInTime = new Date(timestamp || Date.now());
        const istDateStr = checkInTime.toLocaleDateString('en-CA', { timeZone: 'Asia/Kolkata' });
        const istCheckIn = new Date(checkInTime.toLocaleString('en-US', { timeZone: 'Asia/Kolkata' }));
        const istHours = istCheckIn.getHours();
        const istMinutes = istCheckIn.getMinutes();

        // Check Morning Lock: Daily attendance opens at 9:30 AM IST (Admins exempt)
        const isBeforeNineThirty = istHours < 9 || (istHours === 9 && istMinutes < 30);
        if (isBeforeNineThirty && req.user.role !== 'Admin') {
            return res.status(403).json({
                success: false,
                error: 'Attendance check-in is locked. The morning check-in window opens at 9:30 AM IST.'
            });
        }

        const isLateCheckIn = istHours > 10 || (istHours === 10 && istMinutes >= 30);

        const attendanceData = {
            user: req.user.id,
            location: {
                type: 'Point',
                coordinates: [longitude, latitude]
            },
            selfieUrl,
            status: isLateCheckIn ? 'Late' : 'Present',
            timestamp: timestamp || Date.now()
        };

        // Site Engineer / Office Employee Specific Logic
        const isSpclRole = ['Application Engineer', 'Field Application Engineer', 'Service Engineer', 'Office Employee', 'Software Developer', 'Embedded Engineer'].includes(req.user.role);

        if (req.isServiceLocation || isSpclRole) {
            attendanceData.locationName = actualLocationName;
        } else {
            attendanceData.site = siteId;
            attendanceData.distanceFromSite = Math.round(geofence.distanceMeters);
            attendanceData.locationName = actualLocationName;
        }

        // Concurrency & Duplicate Check-In Guard (Idempotency under high load)
        const startOfDay = new Date(`${istDateStr}T00:00:00.000+05:30`);
        const endOfDay = new Date(`${istDateStr}T23:59:59.999+05:30`);

        // Active Work From Home (WFH) & Approved Leave Guard
        const Leave = require('../models/Leave');
        const activeWFH = await Leave.findOne({
            user: req.user.id,
            status: 'Approved',
            leaveType: 'Work From Home (WFH)',
            startDate: { $lte: endOfDay },
            endDate: { $gte: startOfDay }
        });

        if (activeWFH) {
            attendanceData.isWFH = true;
            if (!attendanceData.locationName.includes('(WFH)')) {
                attendanceData.locationName = `${attendanceData.locationName} (WFH Approved)`;
            }
        } else {
            // Active Approved Leave Guard (Blocks punches during authorized vacation/sick leaves)
            const activeApprovedLeave = await Leave.findOne({
                user: req.user.id,
                status: 'Approved',
                startDate: { $lte: endOfDay },
                endDate: { $gte: startOfDay }
            });

            if (activeApprovedLeave) {
                const formattedStart = new Date(activeApprovedLeave.startDate).toLocaleDateString('en-IN', { timeZone: 'Asia/Kolkata', day: '2-digit', month: 'short' });
                const formattedEnd = new Date(activeApprovedLeave.endDate).toLocaleDateString('en-IN', { timeZone: 'Asia/Kolkata', day: '2-digit', month: 'short' });
                const remarkText = activeApprovedLeave.adminRemarks ? ` MD Note: "${activeApprovedLeave.adminRemarks}".` : '';
                return res.status(403).json({
                    success: false,
                    isLeaveLocked: true,
                    error: `Attendance Locked: You are on approved ${activeApprovedLeave.leaveType} (${formattedStart} to ${formattedEnd}).${remarkText} Check-in is disabled during approved leave periods.`
                });
            }
        }

        const existingShift = await Attendance.findOne({
            user: req.user.id,
            timestamp: { $gte: startOfDay, $lte: endOfDay }
        }).sort({ timestamp: -1 });

        if (existingShift) {
            if (!existingShift.checkOut) {
                return res.status(200).json({
                    success: true,
                    data: existingShift,
                    message: 'Active shift already in progress for today.'
                });
            } else {
                return res.status(400).json({
                    success: false,
                    error: "Today's shift has already been concluded. Fresh login will open tomorrow morning."
                });
            }
        }

        attendanceData.dateStr = istDateStr;

        let attendance;
        try {
            attendance = await Attendance.create(attendanceData);
        } catch (createErr) {
            if (createErr.code === 11000) {
                const collisionRecord = await Attendance.findOne({
                    user: req.user.id,
                    timestamp: { $gte: startOfDay, $lte: endOfDay }
                }).sort({ timestamp: -1 });
                if (collisionRecord) {
                    if (!collisionRecord.checkOut) {
                        return res.status(200).json({
                            success: true,
                            data: collisionRecord,
                            message: 'Active shift already in progress for today.'
                        });
                    } else {
                        return res.status(400).json({
                            success: false,
                            error: "Today's shift has already been concluded. Fresh login will open tomorrow morning."
                        });
                    }
                }
            }
            throw createErr;
        }

        // Check for Late Check-In (After 10:30 AM IST) -> Auto-trigger Escalation Warning
        await triggerLateCheckInEscalation(req.user, attendance);

        // Real-time Push to Dashboard
        if (req.app.locals.io) {
            const populatedAttendance = await Attendance.findById(attendance._id)
                .populate('user', 'name email role')
                .populate('site', 'name');
            req.app.locals.io.emit('attendance_logged', populatedAttendance);
        }

        res.status(201).json({
            success: true,
            data: attendance
        });
    } catch (error) {
        next(error);
    }
};

